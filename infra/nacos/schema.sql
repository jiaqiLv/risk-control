-- Nacos PostgreSQL 初始化脚本
-- 在 risk_control 数据库中执行此脚本

CREATE TABLE IF NOT EXISTS config_info (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    data_id varchar(255) NOT NULL,
    group_id varchar(255) NOT NULL,
    content text NOT NULL,
    md5 varchar(32) DEFAULT NULL,
    gmt_create timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    src_user text,
    src_ip varchar(50) DEFAULT NULL,
    app_name varchar(128) DEFAULT NULL,
    tenant_id varchar(128) DEFAULT '',
    c_desc varchar(256) DEFAULT NULL,
    c_use varchar(64) DEFAULT NULL,
    effect varchar(64) DEFAULT NULL,
    type varchar(64) DEFAULT NULL,
    c_schema text,
    encrypted_data_key text NOT NULL DEFAULT '',
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS config_info_aggr (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    data_id varchar(255) NOT NULL,
    group_id varchar(255) NOT NULL,
    datum_id varchar(255) NOT NULL,
    content text NOT NULL,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    app_name varchar(128) DEFAULT NULL,
    tenant_id varchar(128) DEFAULT '',
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS config_info_beta (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    data_id varchar(255) NOT NULL,
    group_id varchar(255) NOT NULL,
    app_name varchar(128) DEFAULT NULL,
    content text NOT NULL,
    beta_ips varchar(1024) DEFAULT NULL,
    md5 varchar(32) DEFAULT NULL,
    gmt_create timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    src_user text,
    src_ip varchar(50) DEFAULT NULL,
    tenant_id varchar(128) DEFAULT '',
    encrypted_data_key text NOT NULL DEFAULT '',
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS config_info_tag (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    data_id varchar(255) NOT NULL,
    group_id varchar(255) NOT NULL,
    tenant_id varchar(128) DEFAULT '',
    tag_id varchar(128) NOT NULL,
    app_name varchar(128) DEFAULT NULL,
    content text NOT NULL,
    md5 varchar(32) DEFAULT NULL,
    gmt_create timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    src_user text,
    src_ip varchar(50) DEFAULT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS config_tags_relation (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tag_name varchar(128) NOT NULL,
    tag_type varchar(64) DEFAULT NULL,
    data_id varchar(255) NOT NULL,
    group_id varchar(255) NOT NULL,
    tenant_id varchar(128) DEFAULT '',
    nid bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    PRIMARY KEY (nid)
);

CREATE TABLE IF NOT EXISTS group_capacity (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    group_id varchar(128) NOT NULL DEFAULT '',
    quota int NOT NULL DEFAULT 0,
    usage int NOT NULL DEFAULT 0,
    max_size int NOT NULL DEFAULT 0,
    max_aggr_count int NOT NULL DEFAULT 0,
    max_aggr_size int NOT NULL DEFAULT 0,
    gmt_create timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE (group_id)
);

CREATE TABLE IF NOT EXISTS his_config_info (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    nid bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    data_id varchar(255) NOT NULL,
    group_id varchar(255) NOT NULL,
    app_name varchar(128) DEFAULT NULL,
    content text NOT NULL,
    md5 varchar(32) DEFAULT NULL,
    gmt_create timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    src_user text,
    src_ip varchar(50) DEFAULT NULL,
    op_type char(10) DEFAULT NULL,
    tenant_id varchar(128) DEFAULT '',
    encrypted_data_key text NOT NULL DEFAULT '',
    PRIMARY KEY (nid)
);

CREATE TABLE IF NOT EXISTS tenant_capacity (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    tenant_id varchar(128) NOT NULL DEFAULT '',
    quota int NOT NULL DEFAULT 0,
    usage int NOT NULL DEFAULT 0,
    max_size int NOT NULL DEFAULT 0,
    max_aggr_count int NOT NULL DEFAULT 0,
    max_aggr_size int NOT NULL DEFAULT 0,
    gmt_create timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE (tenant_id)
);

CREATE TABLE IF NOT EXISTS tenant_info (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    kp varchar(128) NOT NULL,
    tenant_id varchar(128) DEFAULT '',
    tenant_name varchar(128) DEFAULT '',
    tenant_desc varchar(256) DEFAULT NULL,
    create_source varchar(32) DEFAULT NULL,
    gmt_create bigint NOT NULL,
    gmt_modified bigint NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (kp, tenant_id)
);

CREATE TABLE IF NOT EXISTS users (
    username varchar(50) NOT NULL PRIMARY KEY,
    password varchar(500) NOT NULL,
    enabled boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS roles (
    username varchar(50) NOT NULL,
    role varchar(50) NOT NULL,
    PRIMARY KEY (username, role)
);

CREATE TABLE IF NOT EXISTS permissions (
    role varchar(50) NOT NULL,
    resource varchar(255) NOT NULL,
    action varchar(8) NOT NULL,
    PRIMARY KEY (role, resource, action)
);

-- 创建索引
CREATE INDEX IF NOT EXISTS idx_config_info_data_id ON config_info(data_id);
CREATE INDEX IF NOT EXISTS idx_config_info_group_id ON config_info(group_id);
CREATE INDEX IF NOT EXISTS idx_config_info_tenant_id ON config_info(tenant_id);
CREATE INDEX IF NOT EXISTS idx_config_info_aggr_datum_id ON config_info_aggr(data_id, group_id, datum_id);
CREATE INDEX IF NOT EXISTS idx_config_info_aggr_tenant_id ON config_info_aggr(tenant_id);
CREATE INDEX IF NOT EXISTS idx_config_info_beta_data_id ON config_info_beta(data_id, group_id);
CREATE INDEX IF NOT EXISTS idx_config_info_beta_tenant_id ON config_info_beta(tenant_id);
CREATE INDEX IF NOT EXISTS idx_config_info_tag_data_id ON config_info_tag(data_id, group_id);
CREATE INDEX IF NOT EXISTS idx_config_info_tag_tenant_id ON config_info_tag(tenant_id);
CREATE INDEX IF NOT EXISTS idx_config_tags_relation_tenant_id ON config_tags_relation(tenant_id);
CREATE INDEX IF NOT EXISTS idx_his_config_info_data_id ON his_config_info(data_id, group_id);
CREATE INDEX IF NOT EXISTS idx_his_config_info_tenant_id ON his_config_info(tenant_id);

